def lookup_vendor(mac: str) -> str:
    if not mac:
        return "Unknown"
    cleaned = mac.replace("-", ":").replace(".", ":").upper()
    parts = [p for p in cleaned.split(":") if p]
    if len(parts) < 3:
        return "Unknown"
    prefix = ":".join(p.zfill(2) for p in parts[:3])
    return OUI.get(prefix, "Unknown")
